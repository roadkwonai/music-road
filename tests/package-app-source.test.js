'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')

test('app source archive is built from tracked HEAD files and refuses a working version mismatch', { skip: process.platform !== 'darwin' }, async t => {
  const { packageAppSource } = require('../scripts/package-app-source')
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'road-app-source-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  execFileSync('git', ['init', '-q'], { cwd: root })
  execFileSync('git', ['config', 'user.email', 'test@example.com'], { cwd: root })
  execFileSync('git', ['config', 'user.name', 'Road Test'], { cwd: root })
  await fs.writeFile(path.join(root, 'package.json'), JSON.stringify({ version: '1.4.0' }))
  await fs.writeFile(path.join(root, 'tracked.txt'), 'tracked')
  execFileSync('git', ['add', 'package.json', 'tracked.txt'], { cwd: root })
  execFileSync('git', ['commit', '-qm', 'fixture'], { cwd: root })
  await fs.writeFile(path.join(root, 'untracked-secret.txt'), 'not in release')
  const dist = path.join(root, 'dist')
  const result = await packageAppSource(dist, root)
  assert.equal(path.basename(result.path), 'RoadMusic-1.4.0-source.zip')
  const entries = execFileSync('/usr/bin/unzip', ['-Z1', result.path], { encoding: 'utf8' })
  assert.match(entries, /^RoadMusic-1\.4\.0-source\/tracked\.txt$/m)
  assert.doesNotMatch(entries, /untracked-secret/)
  await fs.writeFile(path.join(root, 'package.json'), JSON.stringify({ version: '1.4.1' }))
  await assert.rejects(packageAppSource(dist, root), /HEAD.*package\.json.*version/i)
})
